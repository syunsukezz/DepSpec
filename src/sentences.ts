// 難易度レベル
export type Level = 'Easy' | 'Normal' | 'Hard';

export interface PhraseSeed {
    text: string;                                  // ひらがな
    targets: Record<number, PressureInstruction>;   // ローマ字(キー)位置 -> 強/普通/弱
}

export interface Centenses {
    phrases: PhraseSeed[];
}

