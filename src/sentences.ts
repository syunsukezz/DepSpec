// キー入力エンジン(keygraph)が全角句読点や英字をそのままでは扱えないため、
// 句読点・記号は除去し、カタカナ・漢字・英単語はひらがな読みに置き換えている
// (keygraph の _char_keys_table に無い文字は打鍵できないため。例えば "%" や
// 大文字アルファベットは未対応なので、"パーセント" は読みで書き、英字は小文字にする)。
//
// 1ラウンド(WORD_LISTS の1要素)の長さは難易度で変える: Easy は短い1フレーズ程度、
// Normal はその中間、Hard は長めの1文になるようにする。台本の元の1文(「元文」。
// 句点や言い切りの形で終わる単位。連用形など言い切りでない形で終わる要素は、
// その元文の続きとして次の要素にまたがる)が長すぎる場合は単語の境目で複数ラウンドに
// 分割してよいが、分割した末尾のラウンドに「別の(次の)元文の先頭」を混ぜてはいけない
// (＝1ラウンドの中身は必ず単一の元文由来の文字列だけにする)。Hard で長いラウンドを
// 作りたい場合も、同じ元文が長さの都合で複数要素に分かれているものを1ラウンドに
// 結合するのは良いが、別の元文どうしを結合してはいけない。
//
// 表示用の漢字混じり文と打鍵圧指定は [表示文, 指定, 表示文, 指定, ...] のように
// 交互に並べて書く(pressureWords が偶数番目=表示文/奇数番目=指定として扱う)。
// 表示文と指定を別々の配列にすると、文の区切りを変えるたびに両方の配列を
// 同じ位置でズレなく直す必要があり事故りやすかったため、1つの配列に隣接させて書く形にした。
//
// 打鍵圧指定(奇数番目の要素)は「かな/マーク」の形で書く(pressureSpec.ts)。
// マークは U(強く) / M(普通) / L(弱く) の1文字で、「直前の区間」に適用される。
//   例: "ねこ/U"            → 全体を強く
//       "あい/Lおーえす/U"   → 前半"あい"は弱く、後半"おーえす"は強く
// 末尾に `/` の無いかなが続く場合はそこは指定なし(無印)として扱う。マークを一切付けなければ
// 完全に無指定(アイコン非表示)で動く。書式を間違えると tsc がコンパイルエラーにする
// (pressureWords の型検証、詳細は pressureSpec.ts を参照)。
//
// 打鍵圧マーク(U/M/L)は「文節」ではなく「単語」単位で、1ラウンドにつき強調したい
// 単語を1〜2個だけ選んで U か L を付ける。単語が文の途中にある場合、その単語の
// 直前の区間もマークで閉じる必要がある(区間をまたいで無印のままには出来ない)ため、
// 強調したい単語の前を埋め草として /M(普通) で閉じる。
//   例: 「ペン」だけを強く打たせたい → "この/Mペン/Uは内蔵のIMUから"
//        ("この"は埋め草の/M、実際に強調されるのは「ペン」の1語のみ)
// 単語の前に強調したい語が無ければ埋め草は不要、単語の後ろに続く残りは
// それ以上マークしたい語が無ければ無印のまま(末尾に`/`を付けない)でよい。
//
// 数字は読み仮名ではなく数字そのもの(半角数字)をタイプさせる。単位・助数詞
// (円/名/人/万/ヶ月/年/パーセントなど)は数字ではなく語なのでひらがな読みのままでよい。
//   例: "20名" → "20めい" / "3ヶ月" → "3かげつ" / "40%" → "40ぱーせんと"
//
