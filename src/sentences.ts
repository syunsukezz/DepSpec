function seedsOf(level: Level): PhraseSeed[] {
    const specs = WORD_LISTS[level];
    const displayTexts = DISPLAY_TEXT_LISTS[level];
    if (specs.length !== displayTexts.length) {
        throw new Error(
            `sentences.ts: WORD_LISTS.${level}(${specs.length}件)と DISPLAY_TEXT_LISTS.${level}(${displayTexts.length}件)の件数が一致していません`,
        );
    }
    return specs.map((spec, i) => ({ ...parsePressureSpec(spec), displayText: displayTexts[i] }));
}

