// 句読点・記号は除去し、カタカナ・漢字・英単語はひらがな読みに置き換えている。
// 台本の1行がタイピング表示欄に収まらないほど長い場合は、指定の区切りを
// またがないよう単語の境目で複数フレーズに分割している(長いとローマ字表示が
// キーボード領域と重なってしまうため)。
//
// 打鍵圧指定を「かな/マーク」の形でテキストに直接埋め込む(pressureSpec.ts)。
// マークは U(強く) / M(普通) / L(弱く) の1文字。区間ごとに指定でき、
//   例: "ねこ/U"            → 全体を強く
