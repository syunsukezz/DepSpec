// (会議・セール・授業 / 商談・発表・ようつべ / 演説・説得 の各シーン)。台本側で単語ごとに
// U(強く)/M(普通)/L(弱く)が指定されているので、その指定をそのまま引き継いでいる。
// キー入力エンジン(keygraph)が全角句読点や英字をそのままでは扱えないため、
// 句読点・記号は除去し、カタカナ・漢字・英単語はひらがな読みに置き換えている。
// 台本の1行がタイピング表示欄に収まらないほど長い場合は、指定の区切りを
// またがないよう単語の境目で複数フレーズに分割している(長いとローマ字表示が
// キーボード領域と重なってしまうため)。
//
// 表示用の漢字混じり文と打鍵圧指定は [表示文, 指定, 表示文, 指定, ...] のように
// 交互に並べて書く(pressureWords が偶数番目=表示文/奇数番目=指定として扱う)。
// 表示文と指定を別々の配列にすると、文の区切りを変えるたびに両方の配列を
// 同じ位置でズレなく直す必要があり事故りやすかったため、1つの配列に隣接させて書く形にした。
//
// 打鍵圧指定(奇数番目の要素)は「かな/マーク」の形で書く(pressureSpec.ts)。
// マークは U(強く) / M(普通) / L(弱く) の1文字。区間ごとに指定でき、
//   例: "ねこ/U"            → 全体を強く
//       "あい/Lおーえす/U"   → 前半"あい"は弱く、後半"おーえす"は強く
// 末尾に `/` の無いかなが続く場合はそこは指定なし(無印)として扱う。マークを一切付けなければ
// 完全に無指定(アイコン非表示)で動く。書式を間違えると tsc がコンパイルエラーにする
// (pressureWords の型検証、詳細は pressureSpec.ts を参照)。
// 新しく単語を足す際、打鍵圧を語感から自動で提案してほしい場合は `npm run generate:pressure`
// (scripts/generatePressureTargets.ts) を実行すると候補が表示される。
