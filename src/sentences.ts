// (会議・セール・授業 / 商談・発表・ようつべ / 演説・説得 の各シーン)。
// キー入力エンジン(keygraph)が全角句読点や英字をそのままでは扱えないため、
// 句読点は除去し、句読点のあった位置で文を分割している(タイピング表示欄に収まる長さに
// するため。長い1文のままだとローマ字表示がキーボード領域と重なってしまう)。
// カタカナ・漢字・英単語はひらがな読みに置き換えている。
//
// 打鍵圧指定を「かな/マーク」の形でテキストに直接埋め込む(pressureSpec.ts)。
// マークは U(強く) / M(普通) / L(弱く) の1文字。区間ごとに指定でき、
//   例: "ねこ/U"            → 全体を強く
//       "あい/Lおーえす/U"   → 前半"あい"は弱く、後半"おーえす"は強く
// 末尾に `/` の無いかなが続く場合はそこは指定なし(無印)として扱う。マークを一切付けなければ
// 完全に無指定(アイコン非表示)で動く。書式を間違えると tsc がコンパイルエラーにする
// (pressureWords の型検証、詳細は pressureSpec.ts を参照)。
